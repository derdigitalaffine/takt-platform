import { build } from "esbuild";
import { mkdir, copyFile, readFile, writeFile } from "node:fs/promises";
await mkdir("../app/static/vendor/mantine", { recursive: true });
// Bootstrap owns the page reset. Scope Mantine's default variables to this board.
const css = await readFile("node_modules/@mantine/core/styles.css", "utf8");
await writeFile(
  "../app/static/vendor/mantine/styles.css",
  css
    .slice(css.indexOf("/* This file is automatically generated"))
    .replaceAll(":root,\n:host", "#kanban")
    .replace(
      /:root\[data-mantine-color-scheme='(dark|light)'\],\n:host\(\[data-mantine-color-scheme='\1'\]\)/g,
      "[data-mantine-color-scheme='$1'] #kanban",
    ),
);
for (const [name, path] of [
  ["mantine", "@mantine/core"],
  ["mantine-hooks", "@mantine/hooks"],
  ["react", "react"],
  ["react-dom", "react-dom"],
]) {
  await copyFile(
    `node_modules/${path}/LICENSE`,
    `../app/static/vendor/mantine/${name}.LICENSE`,
  );
}
await build({
  entryPoints: ["board.jsx"],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020"],
  outfile: "../app/static/board-ui.js",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "linked",
});
